// Command genchroma writes the amd64 AVX2 and arm64 NEON assembly for the
// H.264 chroma sample interpolation (package mc: PutChroma, PutChromaPair).
//
// Run from the repository root: go run ./internal/genchroma
//
// The kernels are written from ITU-T H.264 (V16) (06/2026), clause 8.4.2.2.2,
// Equation 8-270 (the bilinear interpolation of the four neighbouring samples
// A, B, C, D with the eighth-sample fractions xFrac and yFrac):
//
//	((8 - xFrac) * (8 - yFrac) * A + xFrac * (8 - yFrac) * B +
//	 (8 - xFrac) * yFrac * C + xFrac * yFrac * D + 32) >> 6
//
// Arithmetic: the expression is the vertical combination of two horizontal
// ones, H(r) = (8 - xFrac) * s[r][x] + xFrac * s[r][x+1] (at most 8 * 255 =
// 2040, one multiply-add of byte pairs), and
// ((8 - yFrac) * H(r) + yFrac * H(r+1) + 32) >> 6, whose largest value, 8 *
// 2040 = 16320, fits sixteen bits: the whole formula is exact in sixteen-bit
// lanes and the result is at most 255, so the final narrowing cannot saturate.
// The row H(r+1) of one output row is the H(r) of the next, so each source row
// is read once. A kernel reads exactly (w + 1) x (h + 1) bytes of each plane
// and writes exactly w x h.
//
// Both chroma planes of a prediction share every parameter, so one call does
// both: the loop over planes is inside the kernel.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

var osExit = os.Exit

type gen struct{ b strings.Builder }

func (g *gen) f(format string, a ...any) { fmt.Fprintf(&g.b, "\t"+format+"\n", a...) }
func (g *gen) l(format string, a ...any) { fmt.Fprintf(&g.b, format+"\n", a...) }

var widths = []int{8, 4, 2}

func name(w int, avg bool) string {
	if avg {
		return fmt.Sprintf("chromaAvg%d", w)
	}
	return fmt.Sprintf("chroma%d", w)
}

// ---------------------------------------------------------------- amd64

// loadH86 reads the row at SI and leaves its horizontal combination in X<d>.
func (g *gen) loadH86(w, d int) {
	switch w {
	case 8:
		g.f("VMOVQ (SI), X1")
		g.f("VMOVQ 1(SI), X2")
	case 4:
		g.f("VMOVD (SI), X1")
		g.f("VMOVD 1(SI), X2")
	default:
		g.f("MOVWLZX (SI), AX")
		g.f("VMOVD AX, X1")
		g.f("MOVWLZX 1(SI), AX")
		g.f("VMOVD AX, X2")
	}
	g.f("VPUNPCKLBW X2, X1, X1")
	g.f("VPMADDUBSW X6, X1, X%d", d)
}

func (g *gen) amd64(w int, avg bool) {
	g.l("// func %sAVX2(dst0, dst1 *byte, dstStride int, src0, src1 *byte, srcStride, h, planes, wx, wy0, wy1 int)", name(w, avg))
	g.l("TEXT ·%sAVX2(SB), NOSPLIT, $0-88", name(w, avg))
	g.f("MOVQ dst0+0(FP), DI")
	g.f("MOVQ dst1+8(FP), R8")
	g.f("MOVQ dstStride+16(FP), DX")
	g.f("MOVQ src0+24(FP), SI")
	g.f("MOVQ src1+32(FP), R9")
	g.f("MOVQ srcStride+40(FP), BX")
	g.f("MOVQ h+48(FP), R10")
	g.f("MOVQ planes+56(FP), CX")
	g.f("MOVQ wx+64(FP), AX")
	g.f("VMOVD AX, X6")
	g.f("VPBROADCASTW X6, X6")
	g.f("MOVQ wy0+72(FP), AX")
	g.f("VMOVD AX, X4")
	g.f("VPBROADCASTW X4, X4")
	g.f("MOVQ wy1+80(FP), AX")
	g.f("VMOVD AX, X7")
	g.f("VPBROADCASTW X7, X7")
	g.f("MOVL $32, AX")
	g.f("VMOVD AX, X9")
	g.f("VPBROADCASTW X9, X9")
	g.l("plane:")
	g.f("MOVQ R10, R11")
	g.loadH86(w, 0)
	g.l("rows:")
	g.f("ADDQ BX, SI")
	g.loadH86(w, 3)
	g.f("VPMULLW X4, X0, X5")
	g.f("VPMULLW X7, X3, X8")
	g.f("VPADDW X8, X5, X5")
	g.f("VPADDW X9, X5, X5")
	g.f("VPSRLW $6, X5, X5")
	g.f("VPACKUSWB X5, X5, X5")
	if avg {
		// (dst + p + 1) >> 1, 8-273: the second prediction of a bi-predicted block
		switch w {
		case 8:
			g.f("VMOVQ (DI), X8")
		case 4:
			g.f("VMOVD (DI), X8")
		default:
			g.f("MOVWLZX (DI), AX")
			g.f("VMOVD AX, X8")
		}
		g.f("VPAVGB X8, X5, X5")
	}
	switch w {
	case 8:
		g.f("VMOVQ X5, (DI)")
	case 4:
		g.f("VMOVD X5, (DI)")
	default:
		g.f("VPEXTRW $0, X5, (DI)")
	}
	g.f("ADDQ DX, DI")
	g.f("VMOVDQA X3, X0")
	g.f("DECQ R11")
	g.f("JNZ rows")
	g.f("DECQ CX")
	g.f("JZ done")
	g.f("MOVQ R8, DI")
	g.f("MOVQ R9, SI")
	g.f("JMP plane")
	g.l("done:")
	g.f("VZEROUPPER")
	g.f("RET")
	g.l("")
}

func (g *gen) amd64File() string {
	g.b.Reset()
	g.l("// Code generated by internal/genchroma; DO NOT EDIT.")
	g.l("")
	g.l("//go:build amd64 && !purego")
	g.l("")
	g.l("#include \"textflag.h\"")
	g.l("")
	for _, avg := range []bool{false, true} {
		for _, w := range widths {
			g.amd64(w, avg)
		}
	}
	return g.b.String()
}

// ---------------------------------------------------------------- arm64

func (g *gen) loadH64(w, d int) {
	switch w {
	case 8:
		g.f("VLD1 (R2), [V1.B8]")
		g.f("ADD $1, R2, R6")
		g.f("VLD1 (R6), [V2.B8]")
	case 4:
		g.f("MOVWU (R2), R7")
		g.f("VMOV R7, V1.S[0]")
		g.f("MOVWU 1(R2), R7")
		g.f("VMOV R7, V2.S[0]")
	default:
		g.f("MOVHU (R2), R7")
		g.f("VMOV R7, V1.H[0]")
		g.f("MOVHU 1(R2), R7")
		g.f("VMOV R7, V2.H[0]")
	}
	g.f("VUMULL V20.B8, V1.B8, V%d.H8", d)
	g.f("VUMLAL V21.B8, V2.B8, V%d.H8", d)
}

func (g *gen) arm64(w int, avg bool) {
	g.l("// func %sNEON(dst0, dst1 *byte, dstStride int, src0, src1 *byte, srcStride, h, planes, wx, wy0, wy1 int)", name(w, avg))
	g.l("TEXT ·%sNEON(SB), NOSPLIT, $0-88", name(w, avg))
	g.f("MOVD dst0+0(FP), R0")
	g.f("MOVD dst1+8(FP), R8")
	g.f("MOVD dstStride+16(FP), R1")
	g.f("MOVD src0+24(FP), R2")
	g.f("MOVD src1+32(FP), R9")
	g.f("MOVD srcStride+40(FP), R3")
	g.f("MOVD h+48(FP), R10")
	g.f("MOVD planes+56(FP), R4")
	g.f("MOVD wx+64(FP), R5")
	g.f("AND $255, R5, R12")
	g.f("LSR $8, R5, R13")
	g.f("VDUP R12, V20.B8")
	g.f("VDUP R13, V21.B8")
	g.f("MOVD wy0+72(FP), R12")
	g.f("VDUP R12, V22.H8")
	g.f("MOVD wy1+80(FP), R12")
	g.f("VDUP R12, V23.H8")
	g.l("plane:")
	g.f("MOVD R10, R11")
	g.loadH64(w, 0)
	g.l("rows:")
	g.f("ADD R3, R2, R2")
	g.loadH64(w, 3)
	g.f("VMUL V22.H8, V0.H8, V5.H8")
	g.f("VMLA V23.H8, V3.H8, V5.H8")
	g.f("VSRSHR $6, V5.H8, V5.H8")
	g.f("VXTN V5.H8, V5.B8")
	if avg {
		// (dst + p + 1) >> 1, 8-273: the second prediction of a bi-predicted block
		switch w {
		case 8:
			g.f("VLD1 (R0), [V6.B8]")
		case 4:
			g.f("MOVWU (R0), R7")
			g.f("VMOV R7, V6.S[0]")
		default:
			g.f("MOVHU (R0), R7")
			g.f("VMOV R7, V6.H[0]")
		}
		g.f("VURHADD V6.B8, V5.B8, V5.B8")
	}
	switch w {
	case 8:
		g.f("VST1 [V5.B8], (R0)")
	case 4:
		g.f("VMOV V5.S[0], R7")
		g.f("MOVW R7, (R0)")
	default:
		g.f("VMOV V5.H[0], R7")
		g.f("MOVH R7, (R0)")
	}
	g.f("ADD R1, R0, R0")
	g.f("VORR V3.B16, V3.B16, V0.B16")
	g.f("SUBS $1, R11, R11")
	g.f("BNE rows")
	g.f("SUBS $1, R4, R4")
	g.f("BEQ done")
	g.f("MOVD R8, R0")
	g.f("MOVD R9, R2")
	g.f("B plane")
	g.l("done:")
	g.f("RET")
	g.l("")
}

func (g *gen) arm64File() string {
	g.b.Reset()
	g.l("// Code generated by internal/genchroma; DO NOT EDIT.")
	g.l("")
	g.l("//go:build arm64 && !purego")
	g.l("")
	g.l("#include \"textflag.h\"")
	g.l("")
	for _, avg := range []bool{false, true} {
		for _, w := range widths {
			g.arm64(w, avg)
		}
	}
	return g.b.String()
}

func files() map[string]string {
	var g gen
	return map[string]string{
		"mc/chroma_amd64.s": g.amd64File(),
		"mc/chroma_arm64.s": g.arm64File(),
	}
}

func run(root string) error {
	for name, body := range files() {
		if err := os.WriteFile(filepath.Join(root, name), []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func main() {
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	if err := run(dir); err != nil {
		fmt.Fprintln(os.Stderr, "genchroma:", err)
		osExit(1)
	}
}
