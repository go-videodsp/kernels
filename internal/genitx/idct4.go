// The 4x4 kernels. Written from ITU-T H.264 (V16) (06/2026): clause 8.5.9
// (scaling of the 4x4 coefficients; Equation 8-336 and the two qP ranges),
// clause 8.5.12 (the 4x4 inverse transform: Equations 8-338 to 8-345 on the
// rows, then on the columns, and the final (x + 32) >> 6), clause 8.5.10 (the
// 4x4 luma DC transform, a pair of Hadamard butterflies, and the scaling of
// Equations 8-326 and 8-327) and clause 8.5.14 (the add to the prediction with
// Clip1).
//
// A call handles the blocks of a 16x16 or 8x8 region selected by a bit mask,
// in the z-scan order of the standard (blocks 4q to 4q+3 make the 8x8
// quadrant q); the constants of the scaling stay in registers across the
// blocks. A block is four vectors: one pass of the transform runs on the four
// rows as registers, a transposition turns rows into columns for the other.

// ---------------------------------------------------------------- amd64

// butterfly4 is the transform of 8.5.12 on four registers s with scratch t,
// in place.
func (g *gen) idct4x(s, t [4]string) {
	g.f("VPADDD %s, %s, %s", s[2], s[0], t[0])
	g.f("VPSUBD %s, %s, %s", s[2], s[0], t[1])
	g.f("VPSRAD $1, %s, %s", s[1], t[2])
	g.f("VPSUBD %s, %s, %s", s[3], t[2], t[2])
	g.f("VPSRAD $1, %s, %s", s[3], t[3])
	g.f("VPADDD %s, %s, %s", s[1], t[3], t[3])
	g.f("VPADDD %s, %s, %s", t[3], t[0], s[0])
	g.f("VPADDD %s, %s, %s", t[2], t[1], s[1])
	g.f("VPSUBD %s, %s, %s", t[2], t[1], s[2])
	g.f("VPSUBD %s, %s, %s", t[3], t[0], s[3])
}

// transpose4x transposes the 4x4 matrix of thirty-two-bit lanes in a, in
// place, with scratch t.
func (g *gen) transpose4x(a, t [4]string) {
	g.f("VPUNPCKLDQ %s, %s, %s", a[1], a[0], t[0])
	g.f("VPUNPCKHDQ %s, %s, %s", a[1], a[0], t[1])
	g.f("VPUNPCKLDQ %s, %s, %s", a[3], a[2], t[2])
	g.f("VPUNPCKHDQ %s, %s, %s", a[3], a[2], t[3])
	g.f("VPUNPCKLQDQ %s, %s, %s", t[2], t[0], a[0])
	g.f("VPUNPCKHQDQ %s, %s, %s", t[2], t[0], a[1])
	g.f("VPUNPCKLQDQ %s, %s, %s", t[3], t[1], a[2])
	g.f("VPUNPCKHQDQ %s, %s, %s", t[3], t[1], a[3])
}

