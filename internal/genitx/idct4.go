// hadamard4x is the butterfly of Equation 8-324's matrix on four registers,
// in place.
func (g *gen) hadamard4x(s, t [4]string) {
	g.f("VPADDD %s, %s, %s", s[3], s[0], t[0])
	g.f("VPADDD %s, %s, %s", s[2], s[1], t[1])
	g.f("VPSUBD %s, %s, %s", s[2], s[1], t[2])
	g.f("VPSUBD %s, %s, %s", s[3], s[0], t[3])
	g.f("VPADDD %s, %s, %s", t[1], t[0], s[0])
	g.f("VPADDD %s, %s, %s", t[2], t[3], s[1])
	g.f("VPSUBD %s, %s, %s", t[1], t[0], s[2])
	g.f("VPSUBD %s, %s, %s", t[2], t[3], s[3])
}

