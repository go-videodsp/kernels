func (g *gen) idct4n(s, t [4]string) {
	g.f("VADD %s.S4, %s.S4, %s.S4", s[2], s[0], t[0])
	g.f("VSUB %s.S4, %s.S4, %s.S4", s[2], s[0], t[1])
	g.f("VSSHR $1, %s.S4, %s.S4", s[1], t[2])
	g.f("VSUB %s.S4, %s.S4, %s.S4", s[3], t[2], t[2])
	g.f("VSSHR $1, %s.S4, %s.S4", s[3], t[3])
	g.f("VADD %s.S4, %s.S4, %s.S4", s[1], t[3], t[3])
	g.f("VADD %s.S4, %s.S4, %s.S4", t[3], t[0], s[0])
	g.f("VADD %s.S4, %s.S4, %s.S4", t[2], t[1], s[1])
	g.f("VSUB %s.S4, %s.S4, %s.S4", t[2], t[1], s[2])
	g.f("VSUB %s.S4, %s.S4, %s.S4", t[3], t[0], s[3])
}

