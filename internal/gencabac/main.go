// Command gencabac writes the amd64 and arm64 assembly of cabac.Decode, the
// decoding of one H.264 CABAC residual block (package cabac).
//
// Run from the repository root: go run ./internal/gencabac
//
// The kernels compute what cabac.decodeRef computes, bin for bin: the
// DecodeDecision and DecodeBypass of ITU-T H.264 (V16) 9.3.3.2.1 and 9.3.3.2.3
// with the offset scaled by 2^7 (see cabac.State), the significance map and
// last flags (7.3.5.3.3), and the levels of 9.3.2.3 (coeff_abs_level_minus1 is
// the unary prefix of 14 context-coded bins and an Exp-Golomb order-0 suffix of
// bypass bins) with the contexts of 9.3.3.1.3. They differ from calling the
// reference once per bin in one way only: range, offset, bit count, stream
// position, the context base, the tables and the loop's own counters stay in
// registers for the whole block, so a decision is a dependent chain of
// loads, a subtract, a compare and a shift with no call, no spill of the
// engine and no bounds check between bins.
//
// The stream is read only when Ptr < len(Data), once per eight shifts, at the
// two places the reference reads it. The tables are indexed by a context byte
// (all 256 values are in range, see cabac/tables.go); the scan tables are
// validated by cabac.NewScan; the coefficient buffer holds nsig+1 entries.
//
// amd64 uses scalar integer instructions only, so there is no CPU dispatch.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

var osExit = os.Exit

type gen struct {
	b strings.Builder
	u int
}

func (g *gen) f(format string, a ...any) { fmt.Fprintf(&g.b, "\t"+format+"\n", a...) }
func (g *gen) l(format string, a ...any) { fmt.Fprintf(&g.b, format+"\n", a...) }
func (g *gen) uid() int                  { g.u++; return g.u }

// offsets inside cabac.State and cabac.engineTables
const (
	offData     = 0
	offLen      = 8
	offPtr      = 24
	offValue    = 32
	offRng      = 36
	offBits     = 40
	offOverflow = 48

	tabNextMPS = 1024
	tabNextLPS = 1280
	tabShift   = 1536
)

const header = "// Code generated by internal/gencabac; DO NOT EDIT.\n\n"

// ---------------------------------------------------------------- amd64
//
// R8 range, R9 value, R10 bits needed, R11 ptr, R12 data, R13 len, SI contexts,
// DI tables; AX, BX, CX, DX, R14 scratch. The decision takes its context index
// in AX and leaves the bin in BX; the bypass leaves it in BX.

func (g *gen) decide86() {
	n := g.uid()
	g.f("MOVBLZX (SI)(AX*1), BX")
	g.f("MOVL R8, CX")
	g.f("SHRL $6, CX")
	g.f("ANDL $3, CX")
	g.f("LEAQ (CX)(BX*4), CX")
	g.f("MOVBLZX (DI)(CX*1), CX")
	g.f("SUBL CX, R8")
	g.f("MOVL R8, DX")
	g.f("SHLL $7, DX")
	g.f("CMPL R9, DX")
	g.f("JCC lps%d", n)
	// most probable symbol
	g.f("MOVBLZX %d(DI)(BX*1), CX", tabNextMPS)
	g.f("MOVB CX, (SI)(AX*1)")
	g.f("MOVL R8, CX")
	g.f("NOTL CX")
	g.f("SHRL $8, CX")
	g.f("ANDL $1, CX")
	g.f("SHLL CX, R8")
	g.f("SHLL CX, R9")
	g.f("ADDQ CX, R10")
	g.f("ANDL $1, BX")
	g.f("TESTQ R10, R10")
	g.f("JMI done%d", n)
	g.f("CMPQ R11, R13")
	g.f("JCC mskip%d", n)
	g.f("MOVBLZX (R12)(R11*1), CX")
	g.f("ORL CX, R9")
	g.l("mskip%d:", n)
	g.f("INCQ R11")
	g.f("MOVQ $-8, R10")
	g.f("JMP done%d", n)
	// least probable symbol
	g.l("lps%d:", n)
	g.f("SUBL DX, R9")
	g.f("MOVL CX, DX")
	g.f("SHRL $3, DX")
	g.f("MOVBLZX %d(DI)(DX*1), R14", tabShift)
	g.f("MOVBLZX %d(DI)(BX*1), DX", tabNextLPS)
	g.f("MOVB DX, (SI)(AX*1)")
	g.f("MOVL CX, R8")
	g.f("MOVQ R14, CX")
	g.f("SHLL CX, R8")
	g.f("SHLL CX, R9")
	g.f("ADDQ CX, R10")
	g.f("ANDL $1, BX")
	g.f("XORL $1, BX")
	g.f("TESTQ R10, R10")
	g.f("JMI done%d", n)
	g.f("CMPQ R11, R13")
	g.f("JCC lskip%d", n)
	g.f("MOVQ R10, CX")
	g.f("MOVBLZX (R12)(R11*1), AX")
	g.f("SHLL CX, AX")
	g.f("ORL AX, R9")
	g.l("lskip%d:", n)
	g.f("INCQ R11")
	g.f("SUBQ $8, R10")
	g.l("done%d:", n)
}

func (g *gen) bypass86() {
	n := g.uid()
	g.f("SHLL $1, R9")
	g.f("INCQ R10")
	g.f("JMI nf%d", n)
	g.f("CMPQ R11, R13")
	g.f("JCC bskip%d", n)
	g.f("MOVBLZX (R12)(R11*1), CX")
	g.f("ORL CX, R9")
	g.l("bskip%d:", n)
	g.f("INCQ R11")
	g.f("MOVQ $-8, R10")
	g.l("nf%d:", n)
	g.f("MOVL R8, DX")
	g.f("SHLL $7, DX")
	g.f("MOVL R9, AX")
	g.f("SUBL DX, AX")
	g.f("XORL BX, BX")
	g.f("CMPL R9, DX")
	g.f("CMOVLCC AX, R9")
	g.f("SETCC BL")
}

// frame slots (amd64): pos[64] at 0, then
const (
	s86I        = 64
	s86N        = 72
	s86Sig      = 80
	s86Last     = 88
	s86Nsig     = 96
	s86Coeffs   = 104
	s86GT1      = 112
	s86EQ1      = 120
	s86K        = 128
	s86Base     = 136
	s86Limit    = 144
	s86St       = 152
	s86Overflow = 160
	s86Prefix   = 168
	s86Value    = 176
	frame86     = 184
)

func amd64() string {
	g := &gen{}
	g.l("%s//go:build amd64 && !purego\n", header)
	g.l("#include \"textflag.h\"\n")
	g.l("// func decodeAsm(st *State, ctx *byte, sig, last *uint16, nsig, levelBase, levelLimit int, coeffs *int32) int")
	g.l("TEXT ·decodeAsm(SB), NOSPLIT, $%d-72", frame86)
	g.f("MOVQ st+0(FP), AX")
	g.f("MOVQ AX, %d(SP)", s86St)
	g.f("MOVQ %d(AX), R12", offData)
	g.f("MOVQ %d(AX), R13", offLen)
	g.f("MOVQ %d(AX), R11", offPtr)
	g.f("MOVL %d(AX), R9", offValue)
	g.f("MOVL %d(AX), R8", offRng)
	g.f("MOVQ %d(AX), R10", offBits)
	g.f("MOVQ ctx+8(FP), SI")
	g.f("LEAQ ·tabs(SB), DI")
	g.f("MOVQ sig+16(FP), AX")
	g.f("MOVQ AX, %d(SP)", s86Sig)
	g.f("MOVQ last+24(FP), AX")
	g.f("MOVQ AX, %d(SP)", s86Last)
	g.f("MOVQ nsig+32(FP), AX")
	g.f("MOVQ AX, %d(SP)", s86Nsig)
	g.f("MOVQ levelBase+40(FP), AX")
	g.f("MOVQ AX, %d(SP)", s86Base)
	g.f("MOVQ levelLimit+48(FP), AX")
	g.f("MOVQ AX, %d(SP)", s86Limit)
	g.f("MOVQ coeffs+56(FP), AX")
	g.f("MOVQ AX, %d(SP)", s86Coeffs)
	g.f("XORQ AX, AX")
	g.f("MOVQ AX, %d(SP)", s86I)
	g.f("MOVQ AX, %d(SP)", s86N)
	g.f("MOVQ AX, %d(SP)", s86Overflow)

	// significance map
	g.l("sigloop:")
	g.f("MOVQ %d(SP), AX", s86I)
	g.f("CMPQ AX, %d(SP)", s86Nsig)
	g.f("JGE notlast")
	g.f("MOVQ %d(SP), DX", s86Sig)
	g.f("MOVWLZX (DX)(AX*2), AX")
	g.decide86()
	g.f("TESTL BX, BX")
	g.f("JEQ nexti")
	g.f("MOVQ %d(SP), AX", s86I)
	g.f("MOVQ %d(SP), DX", s86N)
	g.f("MOVB AL, 0(SP)(DX*1)")
	g.f("INCQ DX")
	g.f("MOVQ DX, %d(SP)", s86N)
	g.f("MOVQ %d(SP), DX", s86Last)
	g.f("MOVWLZX (DX)(AX*2), AX")
	g.decide86()
	g.f("TESTL BX, BX")
	g.f("JNE haslast")
	g.l("nexti:")
	g.f("INCQ %d(SP)", s86I)
	g.f("JMP sigloop")
	g.l("notlast:")
	g.f("MOVQ %d(SP), AX", s86Nsig)
	g.f("MOVQ %d(SP), DX", s86N)
	g.f("MOVB AL, 0(SP)(DX*1)")
	g.f("INCQ DX")
	g.f("MOVQ DX, %d(SP)", s86N)
	g.l("haslast:")

	// levels, last significant coefficient first
	g.f("MOVQ %d(SP), AX", s86N)
	g.f("DECQ AX")
	g.f("MOVQ AX, %d(SP)", s86K)
	g.f("MOVQ $0, %d(SP)", s86GT1)
	g.f("MOVQ $0, %d(SP)", s86EQ1)
	g.l("levelloop:")
	g.f("MOVQ %d(SP), AX", s86Base)
	g.f("MOVQ %d(SP), CX", s86GT1)
	g.f("TESTQ CX, CX")
	g.f("JNE gt1set")
	g.f("MOVQ %d(SP), DX", s86EQ1)
	g.f("INCQ DX")
	g.f("CMPQ DX, $4")
	g.f("JLE inc0ok")
	g.f("MOVQ $4, DX")
	g.l("inc0ok:")
	g.f("ADDQ DX, AX")
	g.l("gt1set:")
	g.f("MOVQ $0, %d(SP)", s86Prefix)
	g.l("prefixloop:")
	g.decide86()
	g.f("TESTL BX, BX")
	g.f("JEQ prefixdone")
	g.f("INCQ %d(SP)", s86Prefix)
	g.f("CMPQ %d(SP), $14", s86Prefix)
	g.f("JGE egolomb")
	g.f("MOVQ %d(SP), DX", s86GT1)
	g.f("MOVQ %d(SP), CX", s86Limit)
	g.f("CMPQ DX, CX")
	g.f("JLE lim")
	g.f("MOVQ CX, DX")
	g.l("lim:")
	g.f("ADDQ %d(SP), DX", s86Base)
	g.f("ADDQ $5, DX")
	g.f("MOVQ DX, AX")
	g.f("JMP prefixloop")
	g.l("prefixdone:")
	g.f("MOVQ %d(SP), AX", s86Prefix)
	g.f("JMP havelevel")
	g.l("egolomb:")
	g.f("MOVQ $14, %d(SP)", s86Value)
	g.f("MOVQ $0, %d(SP)", s86Prefix)
	g.l("egloop:")
	g.bypass86()
	g.f("TESTL BX, BX")
	g.f("JEQ egdone")
	g.f("MOVQ %d(SP), CX", s86Prefix)
	g.f("MOVQ $1, AX")
	g.f("SHLQ CX, AX")
	g.f("ADDQ AX, %d(SP)", s86Value)
	g.f("INCQ CX")
	g.f("MOVQ CX, %d(SP)", s86Prefix)
	g.f("CMPQ CX, $24")
	g.f("JGT egdone")
	g.f("JMP egloop")
	g.l("egdone:")
	g.f("MOVQ %d(SP), CX", s86Prefix)
	g.f("DECQ CX")
	g.l("eglow:")
	g.f("TESTQ CX, CX")
	g.f("JLT egend")
	g.f("MOVQ CX, %d(SP)", s86Prefix)
	g.bypass86()
	g.f("MOVQ %d(SP), CX", s86Prefix)
	g.f("SHLQ CX, BX")
	g.f("ADDQ BX, %d(SP)", s86Value)
	g.f("DECQ CX")
	g.f("JMP eglow")
	g.l("egend:")
	g.f("MOVQ %d(SP), AX", s86Value)
	g.l("havelevel:")
	g.f("INCQ AX")
	g.f("CMPQ AX, $32767")
	g.f("JLE lvok")
	g.f("MOVQ $1, %d(SP)", s86Overflow)
	g.f("MOVQ $32767, AX")
	g.l("lvok:")
	g.f("CMPQ AX, $1")
	g.f("JLE eq1")
	g.f("INCQ %d(SP)", s86GT1)
	g.f("JMP sgn")
	g.l("eq1:")
	g.f("INCQ %d(SP)", s86EQ1)
	g.l("sgn:")
	g.f("MOVQ AX, %d(SP)", s86Value)
	g.bypass86()
	g.f("MOVQ %d(SP), AX", s86Value)
	g.f("NEGQ BX")
	g.f("XORQ BX, AX")
	g.f("SUBQ BX, AX")
	g.f("MOVQ %d(SP), CX", s86K)
	g.f("MOVBLZX 0(SP)(CX*1), DX")
	g.f("MOVQ %d(SP), CX", s86Coeffs)
	g.f("MOVL AX, (CX)(DX*4)")
	g.f("DECQ %d(SP)", s86K)
	g.f("JGE levelloop")

	// epilogue
	g.f("MOVQ %d(SP), AX", s86St)
	g.f("MOVQ R11, %d(AX)", offPtr)
	g.f("MOVL R9, %d(AX)", offValue)
	g.f("MOVL R8, %d(AX)", offRng)
	g.f("MOVQ R10, %d(AX)", offBits)
	g.f("MOVQ %d(SP), CX", s86Overflow)
	g.f("TESTQ CX, CX")
	g.f("JEQ noov")
	g.f("MOVL $1, %d(AX)", offOverflow)
	g.l("noov:")
	g.f("MOVQ %d(SP), AX", s86N)
	g.f("MOVQ AX, ret+64(FP)")
	g.f("RET")
	return g.b.String()
}

// ---------------------------------------------------------------- arm64
//
// R0 contexts, R1 tables, R2 range, R3 value, R4 bits needed, R5 ptr, R6 data,
// R7 len, R8 sig, R9 last, R10 i then k, R11 n, R12 coeffs, R13 numGt1,
// R14 numEq1, R15 level base, R19 nextMPS, R20 nextLPS, R21 shift table, R22
// prefix then k of the suffix; R23 s then the bin, R24 R25 scratch, R26 context
// index. The decision takes the index in R26 and leaves the bin in R23.

func (g *gen) decideA64() {
	n := g.uid()
	g.f("MOVBU (R0)(R26), R23")
	g.f("UBFX $6, R2, $2, R24")
	g.f("ADD R23<<2, R24, R24")
	g.f("MOVBU (R1)(R24), R24")
	g.f("SUBW R24, R2, R2")
	g.f("LSLW $7, R2, R25")
	g.f("CMPW R25, R3")
	g.f("BHS lps%d", n)
	g.f("MOVBU (R19)(R23), R24")
	g.f("MOVB R24, (R0)(R26)")
	g.f("MVNW R2, R24")
	g.f("UBFX $8, R24, $1, R24")
	g.f("LSLW R24, R2, R2")
	g.f("LSLW R24, R3, R3")
	g.f("ADD R24, R4, R4")
	g.f("AND $1, R23, R23")
	g.f("TBNZ $63, R4, done%d", n)
	g.f("CMP R7, R5")
	g.f("BHS mskip%d", n)
	g.f("MOVBU (R6)(R5), R24")
	g.f("ORRW R24, R3, R3")
	g.l("mskip%d:", n)
	g.f("ADD $1, R5")
	g.f("MOVD $-8, R4")
	g.f("B done%d", n)
	g.l("lps%d:", n)
	g.f("SUBW R25, R3, R3")
	g.f("LSR $3, R24, R25")
	g.f("MOVBU (R21)(R25), R25")
	g.f("MOVBU (R20)(R23), R2")
	g.f("MOVB R2, (R0)(R26)")
	g.f("LSLW R25, R24, R2")
	g.f("LSLW R25, R3, R3")
	g.f("ADD R25, R4, R4")
	g.f("AND $1, R23, R23")
	g.f("EOR $1, R23, R23")
	g.f("TBNZ $63, R4, done%d", n)
	g.f("CMP R7, R5")
	g.f("BHS lskip%d", n)
	g.f("MOVBU (R6)(R5), R24")
	g.f("LSLW R4, R24, R24")
	g.f("ORRW R24, R3, R3")
	g.l("lskip%d:", n)
	g.f("ADD $1, R5")
	g.f("SUB $8, R4")
	g.l("done%d:", n)
}

func (g *gen) bypassA64() {
	n := g.uid()
	g.f("LSLW $1, R3, R3")
	g.f("ADD $1, R4, R4")
	g.f("TBNZ $63, R4, nf%d", n)
	g.f("CMP R7, R5")
	g.f("BHS bskip%d", n)
	g.f("MOVBU (R6)(R5), R24")
	g.f("ORRW R24, R3, R3")
	g.l("bskip%d:", n)
	g.f("ADD $1, R5")
	g.f("MOVD $-8, R4")
	g.l("nf%d:", n)
	g.f("LSLW $7, R2, R25")
	g.f("SUBW R25, R3, R24")
	g.f("CMPW R25, R3")
	g.f("CSELW HS, R24, R3, R3")
	g.f("CSETW HS, R23")
}

// frame slots (arm64): pos[64] at 8, then
const (
	sA64Nsig     = 72
	sA64Limit    = 80
	sA64St       = 88
	sA64Overflow = 96
	frameA64     = 104
)

func arm64() string {
	g := &gen{}
	g.l("%s//go:build arm64 && !purego\n", header)
	g.l("#include \"textflag.h\"\n")
	g.l("// func decodeAsm(st *State, ctx *byte, sig, last *uint16, nsig, levelBase, levelLimit int, coeffs *int32) int")
	g.l("TEXT ·decodeAsm(SB), NOSPLIT, $%d-72", frameA64)
	g.f("MOVD st+0(FP), R26")
	g.f("MOVD R26, %d(RSP)", sA64St)
	g.f("MOVD %d(R26), R6", offData)
	g.f("MOVD %d(R26), R7", offLen)
	g.f("MOVD %d(R26), R5", offPtr)
	g.f("MOVWU %d(R26), R3", offValue)
	g.f("MOVWU %d(R26), R2", offRng)
	g.f("MOVD %d(R26), R4", offBits)
	g.f("MOVD ctx+8(FP), R0")
	g.f("MOVD $·tabs(SB), R1")
	g.f("ADD $%d, R1, R19", tabNextMPS)
	g.f("ADD $%d, R1, R20", tabNextLPS)
	g.f("ADD $%d, R1, R21", tabShift)
	g.f("MOVD sig+16(FP), R8")
	g.f("MOVD last+24(FP), R9")
	g.f("MOVD nsig+32(FP), R26")
	g.f("MOVD R26, %d(RSP)", sA64Nsig)
	g.f("MOVD levelBase+40(FP), R15")
	g.f("MOVD levelLimit+48(FP), R26")
	g.f("MOVD R26, %d(RSP)", sA64Limit)
	g.f("MOVD coeffs+56(FP), R12")
	g.f("MOVD $0, R10")
	g.f("MOVD $0, R11")
	g.f("MOVD $0, R26")
	g.f("MOVD R26, %d(RSP)", sA64Overflow)

	g.l("sigloop:")
	g.f("MOVD %d(RSP), R26", sA64Nsig)
	g.f("CMP R26, R10")
	g.f("BGE notlast")
	g.f("MOVHU (R8)(R10<<1), R26")
	g.decideA64()
	g.f("CBZW R23, nexti")
	g.f("ADD $8, RSP, R24")
	g.f("MOVB R10, (R24)(R11)")
	g.f("ADD $1, R11")
	g.f("MOVHU (R9)(R10<<1), R26")
	g.decideA64()
	g.f("CBNZW R23, haslast")
	g.l("nexti:")
	g.f("ADD $1, R10")
	g.f("B sigloop")
	g.l("notlast:")
	g.f("MOVD %d(RSP), R26", sA64Nsig)
	g.f("ADD $8, RSP, R24")
	g.f("MOVB R26, (R24)(R11)")
	g.f("ADD $1, R11")
	g.l("haslast:")

	g.f("SUB $1, R11, R10")
	g.f("MOVD $0, R13")
	g.f("MOVD $0, R14")
	g.l("levelloop:")
	g.f("CBNZ R13, gt1set")
	g.f("ADD $1, R14, R26")
	g.f("MOVD $4, R24")
	g.f("CMP $4, R26")
	g.f("CSEL GT, R24, R26, R26")
	g.f("ADD R15, R26, R26")
	g.f("B go0")
	g.l("gt1set:")
	g.f("MOVD R15, R26")
	g.l("go0:")
	g.f("MOVD $0, R22")
	g.l("prefixloop:")
	g.decideA64()
	g.f("CBZW R23, prefixdone")
	g.f("ADD $1, R22")
	g.f("CMP $14, R22")
	g.f("BGE egolomb")
	g.f("MOVD %d(RSP), R24", sA64Limit)
	g.f("CMP R24, R13")
	g.f("CSEL GT, R24, R13, R26")
	g.f("ADD R15, R26, R26")
	g.f("ADD $5, R26, R26")
	g.f("B prefixloop")
	g.l("prefixdone:")
	g.f("MOVD R22, R26")
	g.f("B havelevel")
	g.l("egolomb:")
	g.f("MOVD $14, R26")
	g.f("MOVD $0, R22")
	g.l("egloop:")
	g.bypassA64()
	g.f("CBZW R23, egdone")
	g.f("MOVD $1, R24")
	g.f("LSL R22, R24, R24")
	g.f("ADD R24, R26, R26")
	g.f("ADD $1, R22")
	g.f("CMP $24, R22")
	g.f("BGT egdone")
	g.f("B egloop")
	g.l("egdone:")
	g.f("SUB $1, R22")
	g.l("eglow:")
	g.f("CMP $0, R22")
	g.f("BLT havelevel")
	g.bypassA64()
	g.f("LSL R22, R23, R23")
	g.f("ADD R23, R26, R26")
	g.f("SUB $1, R22")
	g.f("B eglow")
	g.l("havelevel:")
	g.f("ADD $1, R26")
	g.f("CMP $32767, R26")
	g.f("BLE lvok")
	g.f("MOVD $1, R24")
	g.f("MOVD R24, %d(RSP)", sA64Overflow)
	g.f("MOVD $32767, R26")
	g.l("lvok:")
	g.f("CMP $1, R26")
	g.f("BLE eq1")
	g.f("ADD $1, R13")
	g.f("B sgn")
	g.l("eq1:")
	g.f("ADD $1, R14")
	g.l("sgn:")
	g.bypassA64()
	g.f("NEG R23, R23")
	g.f("EOR R23, R26, R26")
	g.f("SUB R23, R26, R26")
	g.f("ADD $8, RSP, R24")
	g.f("MOVBU (R24)(R10), R24")
	g.f("MOVW R26, (R12)(R24<<2)")
	g.f("SUB $1, R10")
	g.f("CMP $0, R10")
	g.f("BGE levelloop")

	g.f("MOVD %d(RSP), R26", sA64St)
	g.f("MOVD R5, %d(R26)", offPtr)
	g.f("MOVW R3, %d(R26)", offValue)
	g.f("MOVW R2, %d(R26)", offRng)
	g.f("MOVD R4, %d(R26)", offBits)
	g.f("MOVD %d(RSP), R24", sA64Overflow)
	g.f("CBZ R24, noov")
	g.f("MOVW R24, %d(R26)", offOverflow)
	g.l("noov:")
	g.f("MOVD R11, ret+64(FP)")
	g.f("RET")
	return g.b.String()
}

func write(dir string) error {
	for name, text := range map[string]string{
		"decode_amd64.s": amd64(),
		"decode_arm64.s": arm64(),
	} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(text), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func main() {
	if err := write("cabac"); err != nil {
		fmt.Fprintln(os.Stderr, "gencabac:", err)
		osExit(1)
	}
}
