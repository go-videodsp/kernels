package main

// The average of two blocks of samples of the picture, (a + b + 1) >> 1: the default
// weighted sample prediction (ITU-T H.265 (V11) (01/2026), clause 8.5.3.3.4.2, Equation
// 8-264) of two blocks at full-sample positions, where the intermediate samples are the
// reference samples shifted left by shift3 and the result needs no clipping. One
// instruction does it on both targets, rounding included: URHADD (arm64) and VPAVGW (amd64).

// urhadd is URHADD Vd.<T>, Vn.<T>, Vm.<T> on halfwords: 8H when q is 1, 4H when it is 0
// (the Go assembler has no mnemonic for it). Base 0x2e601400: U=1, size=01, opcode 00010
// "rounding halving add", with Q at bit 30.
func urhadd(q, d, n, m int) uint32 {
	return 0x2e601400 | uint32(q)<<30 | uint32(m)<<16 | uint32(n)<<5 | uint32(d)
}

func neonAverage(e *emitter) {
	e.raw("// func averageNEON(dst *uint16, dstStride int, a *uint16, aStride int, b *uint16, bStride, w, h int)\n")
	e.raw("TEXT ·averageNEON(SB), NOSPLIT, $0-64\n")
	e.f("MOVD dst+0(FP), R0")
	e.f("MOVD dstStride+8(FP), R1")
	e.f("MOVD a+16(FP), R2")
	e.f("MOVD aStride+24(FP), R3")
	e.f("MOVD b+32(FP), R4")
	e.f("MOVD bStride+40(FP), R5")
	e.f("MOVD w+48(FP), R6")
	e.f("MOVD h+56(FP), R7")
	e.f("LSL $1, R1, R1")
	e.f("LSL $1, R3, R3")
	e.f("LSL $1, R5, R5")
	e.label("rows")
	e.f("MOVD R2, R8")
	e.f("MOVD R4, R9")
	e.f("MOVD R0, R10")
	e.f("MOVD R6, R11")
	e.label("cols16")
	e.f("CMP $16, R11")
	e.f("BLT tail8")
	e.f("VLD1.P 32(R8), [V0.H8, V1.H8]")
	e.f("VLD1.P 32(R9), [V2.H8, V3.H8]")
	e.f("WORD $0x%08x // URHADD V0.8H, V0.8H, V2.8H", urhadd(1, 0, 0, 2))
	e.f("WORD $0x%08x // URHADD V1.8H, V1.8H, V3.8H", urhadd(1, 1, 1, 3))
	e.f("VST1.P [V0.H8, V1.H8], 32(R10)")
	e.f("SUB $16, R11, R11")
	e.f("B cols16")
	e.label("tail8")
	e.f("CMP $8, R11")
	e.f("BLT tail4")
	e.f("VLD1.P 16(R8), [V0.H8]")
	e.f("VLD1.P 16(R9), [V2.H8]")
	e.f("WORD $0x%08x // URHADD V0.8H, V0.8H, V2.8H", urhadd(1, 0, 0, 2))
	e.f("VST1.P [V0.H8], 16(R10)")
	e.f("SUB $8, R11, R11")
	e.label("tail4")
	e.f("CMP $4, R11")
	e.f("BLT tail2")
	e.f("VLD1.P 8(R8), [V0.H4]")
	e.f("VLD1.P 8(R9), [V2.H4]")
	e.f("WORD $0x%08x // URHADD V0.4H, V0.4H, V2.4H", urhadd(0, 0, 0, 2))
	e.f("VST1.P [V0.H4], 8(R10)")
	e.f("SUB $4, R11, R11")
	e.label("tail2")
	e.f("CBZ R11, next")
	e.f("FMOVS (R8), F0")
	e.f("FMOVS (R9), F2")
	e.f("WORD $0x%08x // URHADD V0.4H, V0.4H, V2.4H (two lanes used)", urhadd(0, 0, 0, 2))
	e.f("FMOVS F0, (R10)")
	e.label("next")
	e.f("ADD R3, R2, R2")
	e.f("ADD R5, R4, R4")
	e.f("ADD R1, R0, R0")
	e.f("SUBS $1, R7, R7")
	e.f("BNE rows")
	e.f("RET")
	e.raw("\n")
}

func avxAverage(e *emitter) {
	e.raw("// func averageAVX2(dst *uint16, dstStride int, a *uint16, aStride int, b *uint16, bStride, w, h int)\n")
	e.raw("TEXT ·averageAVX2(SB), NOSPLIT, $0-64\n")
	e.f("MOVQ dst+0(FP), DI")
	e.f("MOVQ dstStride+8(FP), R8")
	e.f("MOVQ a+16(FP), SI")
	e.f("MOVQ aStride+24(FP), R9")
	e.f("MOVQ b+32(FP), BX")
	e.f("MOVQ bStride+40(FP), R10")
	e.f("MOVQ w+48(FP), CX")
	e.f("MOVQ h+56(FP), DX")
	e.f("SHLQ $1, R8")
	e.f("SHLQ $1, R9")
	e.f("SHLQ $1, R10")
	e.label("rows")
	e.f("MOVQ SI, R12")
	e.f("MOVQ BX, R13")
	e.f("MOVQ DI, AX")
	e.f("MOVQ CX, R11")
	e.label("cols16")
	e.f("CMPQ R11, $16")
	e.f("JLT tail8")
	e.f("VMOVDQU (R12), Y0")
	e.f("VPAVGW (R13), Y0, Y0")
	e.f("VMOVDQU Y0, (AX)")
	e.f("ADDQ $32, R12")
	e.f("ADDQ $32, R13")
	e.f("ADDQ $32, AX")
	e.f("SUBQ $16, R11")
	e.f("JMP cols16")
	e.label("tail8")
	e.f("CMPQ R11, $8")
	e.f("JLT tail4")
	e.f("VMOVDQU (R12), X0")
	e.f("VPAVGW (R13), X0, X0")
	e.f("VMOVDQU X0, (AX)")
	e.f("ADDQ $16, R12")
	e.f("ADDQ $16, R13")
	e.f("ADDQ $16, AX")
	e.f("SUBQ $8, R11")
	e.label("tail4")
	e.f("CMPQ R11, $4")
	e.f("JLT tail2")
	e.f("VMOVQ (R12), X0")
	e.f("VMOVQ (R13), X1")
	e.f("VPAVGW X1, X0, X0")
	e.f("VMOVQ X0, (AX)")
	e.f("ADDQ $8, R12")
	e.f("ADDQ $8, R13")
	e.f("ADDQ $8, AX")
	e.f("SUBQ $4, R11")
	e.label("tail2")
	e.f("TESTQ R11, R11")
	e.f("JZ next")
	e.f("VMOVD (R12), X0")
	e.f("VMOVD (R13), X1")
	e.f("VPAVGW X1, X0, X0")
	e.f("VMOVD X0, (AX)")
	e.label("next")
	e.f("ADDQ R9, SI")
	e.f("ADDQ R10, BX")
	e.f("ADDQ R8, DI")
	e.f("DECQ DX")
	e.f("JNZ rows")
	e.f("VZEROUPPER")
	e.f("RET")
	e.raw("\n")
}
