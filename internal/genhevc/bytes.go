package main

import (
	"fmt"
	"go/format"
)

// formatGo formats generated Go source; an error leaves it empty, which the up-to-date test
// catches.
func formatGo(src string) string {
	formatted, _ := format.Source([]byte(src))
	return string(formatted)
}

// The first (horizontal) pass over the bytes of an 8-bit picture: hpass8B and hpass4B, the
// loop nests of neonH, avxH, neonPass4 and avxPass4 with the loads of vpassu.go's byte forms
// (neonLoadBytes, avxLoadBytes): the taps are one byte apart, the stride is in bytes, and a
// block reads exactly the samples of its footprint.

// neonHB is hpass8BNEON<shift>.
func neonHB(e *emitter, shift int) {
	e.raw(fmt.Sprintf("// func hpass8BNEON%d(dst *int16, dstStride int, src *uint8, srcStride, w, h int, c *int16)\n", shift))
	e.raw(fmt.Sprintf("TEXT ·hpass8BNEON%d(SB), NOSPLIT, $0-56\n", shift))
	neonPrologue(e, 1, 0)
	e.label("rows")
	e.f("MOVD R2, R7")
	e.f("MOVD R0, R8")
	e.f("MOVD R4, R9")
	e.label("cols8")
	e.f("CMP $8, R9")
	e.f("BLT tail")
	e.f("VEOR V0.B16, V0.B16, V0.B16")
	e.f("VEOR V1.B16, V1.B16, V1.B16")
	e.f("MOVD R7, R10")
	for k := 0; k < 8; k++ {
		neonLoadBytes(e, 8, "R10")
		e.f("VSMLAL V%d.H4, V2.H4, V0.S4", 16+k)
		e.f("VSMLAL2 V%d.H8, V2.H8, V1.S4", 16+k)
		if k < 7 {
			e.f("ADD $1, R10, R10")
		}
	}
	if shift > 0 {
		e.f("VSSHR $%d, V0.S4, V0.S4", shift)
		e.f("VSSHR $%d, V1.S4, V1.S4", shift)
	}
	e.f("VXTN V0.S4, V3.H4")
	e.f("VXTN2 V1.S4, V3.H8")
	e.f("VST1 [V3.H8], (R8)")
	e.f("ADD $8, R7, R7")
	e.f("ADD $16, R8, R8")
	e.f("SUB $8, R9, R9")
	e.f("B cols8")
	e.label("tail")
	e.f("CBZ R9, next")
	e.f("VEOR V0.B16, V0.B16, V0.B16")
	e.f("MOVD R7, R10")
	for k := 0; k < 8; k++ {
		neonLoadBytes(e, 4, "R10")
		e.f("VSMLAL V%d.H4, V2.H4, V0.S4", 16+k)
		if k < 7 {
			e.f("ADD $1, R10, R10")
		}
	}
	if shift > 0 {
		e.f("VSSHR $%d, V0.S4, V0.S4", shift)
	}
	e.f("VXTN V0.S4, V3.H4")
	e.f("VST1 [V3.H4], (R8)")
	e.label("next")
	e.f("ADD R3, R2, R2")
	e.f("ADD R1, R0, R0")
	e.f("SUBS $1, R5, R5")
	e.f("BNE rows")
	e.f("RET")
	e.raw("\n")
}

// neonPass4HB is hpass4BNEON<shift>, the chroma twin with groups of 8, 4 and 2 columns.
func neonPass4HB(e *emitter, shift int) {
	e.raw(fmt.Sprintf("// func hpass4BNEON%d(dst *int16, dstStride int, src *uint8, srcStride, w, h int, c *int16)\n", shift))
	e.raw(fmt.Sprintf("TEXT ·hpass4BNEON%d(SB), NOSPLIT, $0-56\n", shift))
	neonPrologue4(e, 1, 0)
	e.label("rows")
	e.f("MOVD R2, R7")
	e.f("MOVD R0, R8")
	e.f("MOVD R4, R9")
	group := func(cols int) {
		half := cols == 8
		e.f("VEOR V0.B16, V0.B16, V0.B16")
		if half {
			e.f("VEOR V1.B16, V1.B16, V1.B16")
		}
		e.f("MOVD R7, R10")
		for k := 0; k < 4; k++ {
			neonLoadBytes(e, cols, "R10")
			e.f("VSMLAL V%d.H4, V2.H4, V0.S4", 16+k)
			if half {
				e.f("VSMLAL2 V%d.H8, V2.H8, V1.S4", 16+k)
			}
			if k < 3 {
				e.f("ADD $1, R10, R10")
			}
		}
		if shift > 0 {
			e.f("VSSHR $%d, V0.S4, V0.S4", shift)
			if half {
				e.f("VSSHR $%d, V1.S4, V1.S4", shift)
			}
		}
		e.f("VXTN V0.S4, V3.H4")
		if half {
			e.f("VXTN2 V1.S4, V3.H8")
		}
		switch cols {
		case 8:
			e.f("VST1 [V3.H8], (R8)")
		case 4:
			e.f("VST1 [V3.H4], (R8)")
		default:
			e.f("FMOVS F3, (R8)")
		}
		e.f("ADD $%d, R7, R7", cols)
		e.f("ADD $%d, R8, R8", 2*cols)
		e.f("SUB $%d, R9, R9", cols)
	}
	e.label("cols8")
	e.f("CMP $8, R9")
	e.f("BLT tail4")
	group(8)
	e.f("B cols8")
	e.label("tail4")
	e.f("CMP $4, R9")
	e.f("BLT tail2")
	group(4)
	e.label("tail2")
	e.f("CBZ R9, next")
	group(2)
	e.label("next")
	e.f("ADD R3, R2, R2")
	e.f("ADD R1, R0, R0")
	e.f("SUBS $1, R5, R5")
	e.f("BNE rows")
	e.f("RET")
	e.raw("\n")
}

// neonHBGo is the Go side of the two: declarations and the tables that pick a kernel by shift.
func neonHBGo() string {
	out := "// Code generated by internal/genhevc; DO NOT EDIT.\n\n//go:build arm64 && !purego\n\npackage hevc\n\n"
	for _, n := range []int{8, 4} {
		for s := 0; s <= 4; s++ {
			out += fmt.Sprintf("//go:noescape\nfunc hpass%dBNEON%d(dst *int16, dstStride int, src *uint8, srcStride, w, h int, c *int16)\n\n", n, s)
		}
		out += fmt.Sprintf("var hpass%dBNEON = [5]func(dst *int16, dstStride int, src *uint8, srcStride, w, h int, c *int16){\n", n)
		for s := 0; s <= 4; s++ {
			out += fmt.Sprintf("\t%d: hpass%dBNEON%d,\n", s, n, s)
		}
		out += "}\n\n"
	}
	return formatGo(out)
}

// avxHB is hpass8BAVX2, the shift an argument in X14.
func avxHB(e *emitter) {
	e.raw("// func hpass8BAVX2(dst *int16, dstStride int, src *uint8, srcStride, w, h int, c *int16, shift int)\n")
	e.raw("TEXT ·hpass8BAVX2(SB), NOSPLIT, $0-64\n")
	avxPrologue(e, 1, 0)
	e.f("MOVQ shift+56(FP), R10")
	e.f("MOVQ R10, X14")
	e.f("VMOVDQU shufmask<>(SB), Y10")
	e.label("rows")
	e.f("MOVQ SI, R12")
	e.f("MOVQ DI, R13")
	e.f("MOVQ CX, R11")
	e.label("cols8")
	e.f("CMPQ R11, $8")
	e.f("JLT tail")
	e.f("VPXOR Y8, Y8, Y8")
	e.f("MOVQ R12, R10")
	for k := 0; k < 8; k++ {
		avxLoadBytes(e, 8, "R10", "9")
		e.f("VPMULLD Y%d, Y9, Y9", k)
		e.f("VPADDD Y9, Y8, Y8")
		if k < 7 {
			e.f("ADDQ $1, R10")
		}
	}
	e.f("VPSRAD X14, Y8, Y8")
	// keep the low 16 bits of each 32-bit lane, as avxH does
	e.f("VPSHUFB Y10, Y8, Y8")
	e.f("VPERMQ $8, Y8, Y8")
	e.f("VMOVDQU X8, (R13)")
	e.f("ADDQ $8, R12")
	e.f("ADDQ $16, R13")
	e.f("SUBQ $8, R11")
	e.f("JMP cols8")
	e.label("tail")
	e.f("TESTQ R11, R11")
	e.f("JZ next")
	e.f("VPXOR X8, X8, X8")
	e.f("MOVQ R12, R10")
	for k := 0; k < 8; k++ {
		avxLoadBytes(e, 4, "R10", "9")
		e.f("VPMULLD X%d, X9, X9", k)
		e.f("VPADDD X9, X8, X8")
		if k < 7 {
			e.f("ADDQ $1, R10")
		}
	}
	e.f("VPSRAD X14, X8, X8")
	e.f("VPSHUFB X10, X8, X8")
	e.f("VMOVQ X8, (R13)")
	e.label("next")
	e.f("ADDQ R9, SI")
	e.f("ADDQ R8, DI")
	e.f("DECQ DX")
	e.f("JNZ rows")
	e.f("VZEROUPPER")
	e.f("RET")
	e.raw("\n")
}

// avxPass4HB is hpass4BAVX2, the chroma twin with groups of 8, 4 and 2 columns.
func avxPass4HB(e *emitter) {
	e.raw("// func hpass4BAVX2(dst *int16, dstStride int, src *uint8, srcStride, w, h int, c *int16, shift int)\n")
	e.raw("TEXT ·hpass4BAVX2(SB), NOSPLIT, $0-64\n")
	avxPrologue4(e, 1, 0)
	e.f("MOVQ shift+56(FP), R10")
	e.f("MOVQ R10, X14")
	e.f("VMOVDQU shufmask<>(SB), Y10")
	e.label("rows")
	e.f("MOVQ SI, R12")
	e.f("MOVQ DI, R13")
	e.f("MOVQ CX, R11")
	group := func(cols int) {
		reg, acc := "Y", "Y8"
		if cols < 8 {
			reg, acc = "X", "X8"
		}
		e.f("VPXOR %s, %s, %s", acc, acc, acc)
		e.f("MOVQ R12, R10")
		for k := 0; k < 4; k++ {
			avxLoadBytes(e, cols, "R10", "9")
			e.f("VPMULLD %s%d, %s9, %s9", reg, k, reg, reg)
			e.f("VPADDD %s9, %s, %s", reg, acc, acc)
			if k < 3 {
				e.f("ADDQ $1, R10")
			}
		}
		e.f("VPSRAD X14, %s, %s", acc, acc)
		e.f("VPSHUFB %s10, %s, %s", reg, acc, acc)
		if cols == 8 {
			e.f("VPERMQ $8, Y8, Y8")
		}
		switch cols {
		case 8:
			e.f("VMOVDQU X8, (R13)")
		case 4:
			e.f("VMOVQ X8, (R13)")
		default:
			e.f("VMOVD X8, (R13)")
		}
		e.f("ADDQ $%d, R12", cols)
		e.f("ADDQ $%d, R13", 2*cols)
		e.f("SUBQ $%d, R11", cols)
	}
	e.label("cols8")
	e.f("CMPQ R11, $8")
	e.f("JLT tail4")
	group(8)
	e.f("JMP cols8")
	e.label("tail4")
	e.f("CMPQ R11, $4")
	e.f("JLT tail2")
	group(4)
	e.label("tail2")
	e.f("TESTQ R11, R11")
	e.f("JZ next")
	group(2)
	e.label("next")
	e.f("ADDQ R9, SI")
	e.f("ADDQ R8, DI")
	e.f("DECQ DX")
	e.f("JNZ rows")
	e.f("VZEROUPPER")
	e.f("RET")
	e.raw("\n")
}
