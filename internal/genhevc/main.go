// Command genhevc writes the assembly of package hevc: the arm64 NEON and the
// amd64 AVX2 kernels of the eight-tap separable filter passes of HEVC luma
// interpolation (ITU-T H.265 (V11) (01/2026), clause 8.5.3.3.3.2, Equations 8-224
// to 8-238).
//
// Run from the repository root: go run ./internal/genhevc
//
// The kernels are written from the equations of the text and from
// docs/design/hevc-passes.md, not from any decoder. Each is a plain loop nest:
// for each row, columns in groups of eight (NEON: SMLAL and SMLAL2 on the two
// halves of the eight samples; AVX2: VPMULLD on eight 32-bit lanes), then one
// group of four. The width is a multiple of four, so no sample past the
// footprint is read and none past the block is written.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type emitter struct{ b strings.Builder }

func (e *emitter) f(format string, a ...any) { fmt.Fprintf(&e.b, "\t"+format+"\n", a...) }
func (e *emitter) label(s string)            { fmt.Fprintf(&e.b, "%s:\n", s) }
func (e *emitter) raw(s string)              { e.b.WriteString(s) }

const header = "// Code generated by internal/genhevc; DO NOT EDIT.\n\n//go:build %s && !purego\n\n#include \"textflag.h\"\n\n"

// ---- arm64 ----

// neonH is hpass8NEON<shift>: dst[y*dstStride+x] = int16((sum_k c[k]*src[y*srcStride+x+k]) >> shift),
// src pointing at the leftmost tap of the first output.
func neonH(e *emitter, shift int) {
	e.raw(fmt.Sprintf("// func hpass8NEON%d(dst *int16, dstStride int, src *uint16, srcStride, w, h int, c *int16)\n", shift))
	e.raw(fmt.Sprintf("TEXT ·hpass8NEON%d(SB), NOSPLIT, $0-56\n", shift))
	neonPrologue(e, 1, 1)
	e.label("rows")
	e.f("MOVD R2, R7")
	e.f("MOVD R0, R8")
	e.f("MOVD R4, R9")
	e.label("cols8")
	e.f("CMP $8, R9")
	e.f("BLT tail")
	e.f("VEOR V0.B16, V0.B16, V0.B16")
	e.f("VEOR V1.B16, V1.B16, V1.B16")
	e.f("MOVD R7, R10")
	for k := 0; k < 8; k++ {
		e.f("VLD1 (R10), [V2.H8]")
		e.f("VSMLAL V%d.H4, V2.H4, V0.S4", 16+k)
		e.f("VSMLAL2 V%d.H8, V2.H8, V1.S4", 16+k)
		if k < 7 {
			e.f("ADD $2, R10, R10")
		}
	}
	if shift > 0 {
		e.f("VSSHR $%d, V0.S4, V0.S4", shift)
		e.f("VSSHR $%d, V1.S4, V1.S4", shift)
	}
	e.f("VXTN V0.S4, V3.H4")
	e.f("VXTN2 V1.S4, V3.H8")
	e.f("VST1 [V3.H8], (R8)")
	e.f("ADD $16, R7, R7")
	e.f("ADD $16, R8, R8")
	e.f("SUB $8, R9, R9")
	e.f("B cols8")
	e.label("tail")
	e.f("CBZ R9, next")
	e.f("VEOR V0.B16, V0.B16, V0.B16")
	e.f("MOVD R7, R10")
	for k := 0; k < 8; k++ {
		e.f("VLD1 (R10), [V2.H4]")
		e.f("VSMLAL V%d.H4, V2.H4, V0.S4", 16+k)
		if k < 7 {
			e.f("ADD $2, R10, R10")
		}
	}
	if shift > 0 {
		e.f("VSSHR $%d, V0.S4, V0.S4", shift)
	}
	e.f("VXTN V0.S4, V3.H4")
	e.f("VST1 [V3.H4], (R8)")
	e.label("next")
	e.f("ADD R3, R2, R2")
	e.f("ADD R1, R0, R0")
	e.f("SUBS $1, R5, R5")
	e.f("BNE rows")
	e.f("RET")
	e.raw("\n")
}

// neonV is vpass8NEON: dst[y*dstStride+x] = (sum_k c[k]*src[(y+k)*srcStride+x]) >> 6 on int16
// intermediates into int32, src pointing at the topmost tap row of the first output.
func neonV(e *emitter) {
	e.raw("// func vpass8NEON(dst *int32, dstStride int, src *int16, srcStride, w, h int, c *int16)\n")
	e.raw("TEXT ·vpass8NEON(SB), NOSPLIT, $0-56\n")
	neonPrologue(e, 2, 1)
	e.label("rows")
	e.f("MOVD R2, R7")
	e.f("MOVD R0, R8")
	e.f("MOVD R4, R9")
	e.label("cols8")
	e.f("CMP $8, R9")
	e.f("BLT tail")
	e.f("VEOR V0.B16, V0.B16, V0.B16")
	e.f("VEOR V1.B16, V1.B16, V1.B16")
	e.f("MOVD R7, R10")
	for k := 0; k < 8; k++ {
		e.f("VLD1 (R10), [V2.H8]")
		e.f("VSMLAL V%d.H4, V2.H4, V0.S4", 16+k)
		e.f("VSMLAL2 V%d.H8, V2.H8, V1.S4", 16+k)
		if k < 7 {
			e.f("ADD R3, R10, R10")
		}
	}
	e.f("VSSHR $6, V0.S4, V0.S4")
	e.f("VSSHR $6, V1.S4, V1.S4")
	e.f("VST1 [V0.S4, V1.S4], (R8)")
	e.f("ADD $16, R7, R7")
	e.f("ADD $32, R8, R8")
	e.f("SUB $8, R9, R9")
	e.f("B cols8")
	e.label("tail")
	e.f("CBZ R9, next")
	e.f("VEOR V0.B16, V0.B16, V0.B16")
	e.f("MOVD R7, R10")
	for k := 0; k < 8; k++ {
		e.f("VLD1 (R10), [V2.H4]")
		e.f("VSMLAL V%d.H4, V2.H4, V0.S4", 16+k)
		if k < 7 {
			e.f("ADD R3, R10, R10")
		}
	}
	e.f("VSSHR $6, V0.S4, V0.S4")
	e.f("VST1 [V0.S4], (R8)")
	e.label("next")
	e.f("ADD R3, R2, R2")
	e.f("ADD R1, R0, R0")
	e.f("SUBS $1, R5, R5")
	e.f("BNE rows")
	e.f("RET")
	e.raw("\n")
}

// neonPrologue loads the seven arguments and the eight coefficient vectors V16..V23, and turns
// the strides into bytes (dstShift and srcShift are log2 of the element sizes).
func neonPrologue(e *emitter, dstShift, srcShift int) {
	e.f("MOVD dst+0(FP), R0")
	e.f("MOVD dstStride+8(FP), R1")
	e.f("MOVD src+16(FP), R2")
	e.f("MOVD srcStride+24(FP), R3")
	e.f("MOVD w+32(FP), R4")
	e.f("MOVD h+40(FP), R5")
	e.f("MOVD c+48(FP), R6")
	e.f("LSL $%d, R1, R1", dstShift)
	e.f("LSL $%d, R3, R3", srcShift)
	for k := 0; k < 8; k++ {
		e.f("VLD1R (R6), [V%d.H8]", 16+k)
		if k < 7 {
			e.f("ADD $2, R6, R6")
		}
	}
}

// ---- amd64 ----

// avxH is hpass8AVX2: the shift is an argument (a count in X14).
func avxH(e *emitter) {
	e.raw("// func hpass8AVX2(dst *int16, dstStride int, src *uint16, srcStride, w, h int, c *int16, shift int)\n")
	e.raw("TEXT ·hpass8AVX2(SB), NOSPLIT, $0-64\n")
	avxPrologue(e, 1, 1)
	e.f("MOVQ shift+56(FP), R10")
	e.f("MOVQ R10, X14")
	e.f("VMOVDQU shufmask<>(SB), Y10")
	e.label("rows")
	e.f("MOVQ SI, R12")
	e.f("MOVQ DI, R13")
	e.f("MOVQ CX, R11")
	e.label("cols8")
	e.f("CMPQ R11, $8")
	e.f("JLT tail")
	e.f("VPXOR Y8, Y8, Y8")
	e.f("MOVQ R12, R10")
	for k := 0; k < 8; k++ {
		e.f("VPMOVZXWD (R10), Y9")
		e.f("VPMULLD Y%d, Y9, Y9", k)
		e.f("VPADDD Y9, Y8, Y8")
		if k < 7 {
			e.f("ADDQ $2, R10")
		}
	}
	e.f("VPSRAD X14, Y8, Y8")
	// keep the low 16 bits of each 32-bit lane (the truncation the reference and the
	// NEON kernel do; VPACKSSDW would saturate), then gather the two lanes' words
	e.f("VPSHUFB Y10, Y8, Y8")
	e.f("VPERMQ $8, Y8, Y8")
	e.f("VMOVDQU X8, (R13)")
	e.f("ADDQ $16, R12")
	e.f("ADDQ $16, R13")
	e.f("SUBQ $8, R11")
	e.f("JMP cols8")
	e.label("tail")
	e.f("TESTQ R11, R11")
	e.f("JZ next")
	e.f("VPXOR X8, X8, X8")
	e.f("MOVQ R12, R10")
	for k := 0; k < 8; k++ {
		e.f("VPMOVZXWD (R10), X9")
		e.f("VPMULLD X%d, X9, X9", k)
		e.f("VPADDD X9, X8, X8")
		if k < 7 {
			e.f("ADDQ $2, R10")
		}
	}
	e.f("VPSRAD X14, X8, X8")
	e.f("VPSHUFB X10, X8, X8")
	e.f("VMOVQ X8, (R13)")
	e.label("next")
	e.f("ADDQ R9, SI")
	e.f("ADDQ R8, DI")
	e.f("DECQ DX")
	e.f("JNZ rows")
	e.f("VZEROUPPER")
	e.f("RET")
	e.raw("\n")
}

// avxV is vpass8AVX2: int16 intermediates to int32, shift 6.
func avxV(e *emitter) {
	e.raw("// func vpass8AVX2(dst *int32, dstStride int, src *int16, srcStride, w, h int, c *int16)\n")
	e.raw("TEXT ·vpass8AVX2(SB), NOSPLIT, $0-56\n")
	avxPrologue(e, 2, 1)
	e.label("rows")
	e.f("MOVQ SI, R12")
	e.f("MOVQ DI, R13")
	e.f("MOVQ CX, R11")
	e.label("cols8")
	e.f("CMPQ R11, $8")
	e.f("JLT tail")
	e.f("VPXOR Y8, Y8, Y8")
	e.f("MOVQ R12, R10")
	for k := 0; k < 8; k++ {
		e.f("VPMOVSXWD (R10), Y9")
		e.f("VPMULLD Y%d, Y9, Y9", k)
		e.f("VPADDD Y9, Y8, Y8")
		if k < 7 {
			e.f("ADDQ R9, R10")
		}
	}
	e.f("VPSRAD $6, Y8, Y8")
	e.f("VMOVDQU Y8, (R13)")
	e.f("ADDQ $16, R12")
	e.f("ADDQ $32, R13")
	e.f("SUBQ $8, R11")
	e.f("JMP cols8")
	e.label("tail")
	e.f("TESTQ R11, R11")
	e.f("JZ next")
	e.f("VPXOR X8, X8, X8")
	e.f("MOVQ R12, R10")
	for k := 0; k < 8; k++ {
		e.f("VPMOVSXWD (R10), X9")
		e.f("VPMULLD X%d, X9, X9", k)
		e.f("VPADDD X9, X8, X8")
		if k < 7 {
			e.f("ADDQ R9, R10")
		}
	}
	e.f("VPSRAD $6, X8, X8")
	e.f("VMOVDQU X8, (R13)")
	e.label("next")
	e.f("ADDQ R9, SI")
	e.f("ADDQ R8, DI")
	e.f("DECQ DX")
	e.f("JNZ rows")
	e.f("VZEROUPPER")
	e.f("RET")
	e.raw("\n")
}

func avxPrologue(e *emitter, dstShift, srcShift int) {
	e.f("MOVQ dst+0(FP), DI")
	e.f("MOVQ dstStride+8(FP), R8")
	e.f("MOVQ src+16(FP), SI")
	e.f("MOVQ srcStride+24(FP), R9")
	e.f("MOVQ w+32(FP), CX")
	e.f("MOVQ h+40(FP), DX")
	e.f("MOVQ c+48(FP), AX")
	e.f("SHLQ $%d, R8", dstShift)
	e.f("SHLQ $%d, R9", srcShift)
	for k := 0; k < 8; k++ {
		e.f("MOVWQSX %d(AX), R10", 2*k)
		e.f("MOVQ R10, X%d", k)
		e.f("VPBROADCASTD X%d, Y%d", k, k)
	}
}

// files is every file the generator writes, by path from the repository root.
func files() map[string]string {
	var a, x emitter
	a.raw(fmt.Sprintf(header, "arm64"))
	for s := 0; s <= 4; s++ {
		neonH(&a, s)
	}
	neonV(&a)
	for s := 0; s <= 4; s++ {
		neonPass4(&a, false, s)
	}
	neonPass4(&a, true, 0)
	x.raw(fmt.Sprintf(header, "amd64"))
	// the byte shuffle that keeps the low word of each dword: bytes 0 1 4 5 8 9 12 13, the
	// rest zeroed (bit 7 set), in each 128-bit lane
	x.raw("DATA shufmask<>+0(SB)/8, $0x0d0c090805040100\nDATA shufmask<>+8(SB)/8, $0x8080808080808080\n" +
		"DATA shufmask<>+16(SB)/8, $0x0d0c090805040100\nDATA shufmask<>+24(SB)/8, $0x8080808080808080\n" +
		"GLOBL shufmask<>(SB), RODATA|NOPTR, $32\n\n")
	avxH(&x)
	avxV(&x)
	avxPass4(&x, false)
	avxPass4(&x, true)
	return map[string]string{"hevc/pass_arm64.s": a.b.String(), "hevc/pass_amd64.s": x.b.String()}
}

var osExit = os.Exit

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	for name, text := range files() {
		if err := os.WriteFile(filepath.Join(root, name), []byte(text), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			osExit(1)
			return
		}
	}
}
