package main

import (
	"fmt"
	"go/format"
)

// The vertical filter over the 16-bit samples of a picture, for a block whose fractional
// position is vertical only (ITU-T H.265 (V11) (01/2026), clauses 8.5.3.3.3.2 and 8.5.3.3.3.3,
// Equations 8-228 and 8-244 and their chroma twins): the sum of the taps times the samples one
// row apart, shifted right by shift1 = bitDepth - 8, into int32. It is vpass of the second stage
// of the two-dimensional filter with uint16 for int16 (the same instructions on samples that fit
// 15 bits) and the shift an argument, so the loop nests are neonV and avxV's.

// neonVU writes vpassU<taps>NEON<shift>: taps 8 (luma) or 4 (chroma, widths even).
func neonVU(e *emitter, ntaps, shift int) {
	name := fmt.Sprintf("vpassU%dNEON%d", ntaps, shift)
	e.raw(fmt.Sprintf("// func %s(dst *int32, dstStride int, src *uint16, srcStride, w, h int, c *int16)\n", name))
	e.raw(fmt.Sprintf("TEXT ·%s(SB), NOSPLIT, $0-56\n", name))
	e.f("MOVD dst+0(FP), R0")
	e.f("MOVD dstStride+8(FP), R1")
	e.f("MOVD src+16(FP), R2")
	e.f("MOVD srcStride+24(FP), R3")
	e.f("MOVD w+32(FP), R4")
	e.f("MOVD h+40(FP), R5")
	e.f("MOVD c+48(FP), R6")
	e.f("LSL $2, R1, R1")
	e.f("LSL $1, R3, R3")
	for k := 0; k < ntaps; k++ {
		e.f("VLD1R (R6), [V%d.H8]", 16+k)
		if k < ntaps-1 {
			e.f("ADD $2, R6, R6")
		}
	}
	e.label("rows")
	e.f("MOVD R2, R7")
	e.f("MOVD R0, R8")
	e.f("MOVD R4, R9")
	group := func(cols int) {
		half := cols == 8
		e.f("VEOR V0.B16, V0.B16, V0.B16")
		if half {
			e.f("VEOR V1.B16, V1.B16, V1.B16")
		}
		e.f("MOVD R7, R10")
		for k := 0; k < ntaps; k++ {
			switch cols {
			case 8:
				e.f("VLD1 (R10), [V2.H8]")
			case 4:
				e.f("VLD1 (R10), [V2.H4]")
			default:
				e.f("FMOVS (R10), F2")
			}
			e.f("VSMLAL V%d.H4, V2.H4, V0.S4", 16+k)
			if half {
				e.f("VSMLAL2 V%d.H8, V2.H8, V1.S4", 16+k)
			}
			if k < ntaps-1 {
				e.f("ADD R3, R10, R10")
			}
		}
		if shift > 0 {
			e.f("VSSHR $%d, V0.S4, V0.S4", shift)
			if half {
				e.f("VSSHR $%d, V1.S4, V1.S4", shift)
			}
		}
		switch cols {
		case 8:
			e.f("VST1 [V0.S4, V1.S4], (R8)")
		case 4:
			e.f("VST1 [V0.S4], (R8)")
		default:
			e.f("FMOVD F0, (R8)")
		}
		e.f("ADD $%d, R7, R7", 2*cols)
		e.f("ADD $%d, R8, R8", 4*cols)
		e.f("SUB $%d, R9, R9", cols)
	}
	e.label("cols8")
	e.f("CMP $8, R9")
	e.f("BLT tail4")
	group(8)
	e.f("B cols8")
	e.label("tail4")
	e.f("CMP $4, R9")
	e.f("BLT tail2")
	group(4)
	e.label("tail2")
	e.f("CBZ R9, next")
	group(2)
	e.label("next")
	e.f("ADD R3, R2, R2")
	e.f("ADD R1, R0, R0")
	e.f("SUBS $1, R5, R5")
	e.f("BNE rows")
	e.f("RET")
	e.raw("\n")
}

// neonVUGo is the Go side: the declarations and the tables that pick a kernel by shift.
func neonVUGo() string {
	out := "// Code generated by internal/genhevc; DO NOT EDIT.\n\n//go:build arm64 && !purego\n\npackage hevc\n\n"
	for _, n := range []int{8, 4} {
		for s := 0; s <= 4; s++ {
			out += fmt.Sprintf("//go:noescape\nfunc vpassU%dNEON%d(dst *int32, dstStride int, src *uint16, srcStride, w, h int, c *int16)\n\n", n, s)
		}
		out += fmt.Sprintf("var vpassU%dNEON = [5]func(dst *int32, dstStride int, src *uint16, srcStride, w, h int, c *int16){\n", n)
		for s := 0; s <= 4; s++ {
			out += fmt.Sprintf("\t%d: vpassU%dNEON%d,\n", s, n, s)
		}
		out += "}\n\n"
	}
	formatted, _ := format.Source([]byte(out)) // an error leaves it empty, which the up-to-date test catches
	return string(formatted)
}

// avxVU writes vpassU8AVX2 or vpassU4AVX2, the shift an argument in X14.
func avxVU(e *emitter, ntaps int) {
	name := fmt.Sprintf("vpassU%dAVX2", ntaps)
	e.raw(fmt.Sprintf("// func %s(dst *int32, dstStride int, src *uint16, srcStride, w, h int, c *int16, shift int)\n", name))
	e.raw(fmt.Sprintf("TEXT ·%s(SB), NOSPLIT, $0-64\n", name))
	e.f("MOVQ dst+0(FP), DI")
	e.f("MOVQ dstStride+8(FP), R8")
	e.f("MOVQ src+16(FP), SI")
	e.f("MOVQ srcStride+24(FP), R9")
	e.f("MOVQ w+32(FP), CX")
	e.f("MOVQ h+40(FP), DX")
	e.f("MOVQ c+48(FP), AX")
	e.f("SHLQ $2, R8")
	e.f("SHLQ $1, R9")
	for k := 0; k < ntaps; k++ {
		e.f("MOVWQSX %d(AX), R10", 2*k)
		e.f("MOVQ R10, X%d", k)
		e.f("VPBROADCASTD X%d, Y%d", k, k)
	}
	e.f("MOVQ shift+56(FP), R10")
	e.f("MOVQ R10, X14")
	e.label("rows")
	e.f("MOVQ SI, R12")
	e.f("MOVQ DI, R13")
	e.f("MOVQ CX, R11")
	group := func(cols int) {
		reg, acc := "Y", "Y8"
		if cols < 8 {
			reg, acc = "X", "X8"
		}
		e.f("VPXOR %s, %s, %s", acc, acc, acc)
		e.f("MOVQ R12, R10")
		for k := 0; k < ntaps; k++ {
			switch cols {
			case 8, 4:
				e.f("VPMOVZXWD (R10), %s9", reg)
			default:
				e.f("VMOVD (R10), X9")
				e.f("VPMOVZXWD X9, X9")
			}
			e.f("VPMULLD %s%d, %s9, %s9", reg, k, reg, reg)
			e.f("VPADDD %s9, %s, %s", reg, acc, acc)
			if k < ntaps-1 {
				e.f("ADDQ R9, R10")
			}
		}
		e.f("VPSRAD X14, %s, %s", acc, acc)
		switch cols {
		case 8:
			e.f("VMOVDQU Y8, (R13)")
		case 4:
			e.f("VMOVDQU X8, (R13)")
		default:
			e.f("VMOVQ X8, (R13)")
		}
		e.f("ADDQ $%d, R12", 2*cols)
		e.f("ADDQ $%d, R13", 4*cols)
		e.f("SUBQ $%d, R11", cols)
	}
	e.label("cols8")
	e.f("CMPQ R11, $8")
	e.f("JLT tail4")
	group(8)
	e.f("JMP cols8")
	e.label("tail4")
	e.f("CMPQ R11, $4")
	e.f("JLT tail2")
	group(4)
	e.label("tail2")
	e.f("TESTQ R11, R11")
	e.f("JZ next")
	group(2)
	e.label("next")
	e.f("ADDQ R9, SI")
	e.f("ADDQ R8, DI")
	e.f("DECQ DX")
	e.f("JNZ rows")
	e.f("VZEROUPPER")
	e.f("RET")
	e.raw("\n")
}
