// Package hevc holds the kernels of HEVC (ITU-T H.265 (V11) (01/2026)) decoding:
// for now the two passes of the eight-tap luma interpolation filter, clause
// 8.5.3.3.3.2, on 16-bit samples.
//
// HPass8 is the horizontal filter of Equations 8-224 to 8-226 over uint16 samples
// with the 14-bit-intermediate shift of the text, shift1 = bitDepth - 8, producing
// int16 values; VPass8 is the vertical filter over int16 intermediates with
// shift2 = 6 (Equations 8-230 to 8-238), producing int32. The filter coefficients
// are an argument: the three luma filters of the text, or any other set whose
// results fit the types below.
//
// On arm64 they run NEON kernels and on amd64 AVX2 kernels, both generated by
// internal/genhevc (go generate); on every other target, and with the purego tag,
// they run the portable reference. All three are bit-exact for the inputs the
// contract below allows.
//
// Contract. Samples are below 1 << bitDepth with bitDepth 8 to 12 (the kernels
// treat them as signed 16-bit numbers, so no sample may exceed 32767, and the
// results of a pass should fit its output type: with the HEVC filters and these bit
// depths, HPass8 gives values in -6144..22528, which fit int16). Outside that
// the three implementations still agree, for samples up to 32767: a sum that does
// not fit keeps its low 16 bits. The Try forms check the bit depth, the geometry
// and the memory; they cannot afford to scan the values, so samples above 32767
// give an unspecified (but memory-safe) result.
// A refusal is an error and nothing is written; no entry point reads or writes
// outside the footprint it proved.
